def download_all_papers(target_dir="research/papers/pdfs"):
    """
    Downloads all open-access research papers to target_dir.
    """
    os.makedirs(target_dir, exist_ok=True)
    headers = {
        "User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36 DeepShield-Research-Bot/1.0"
    }

    print("=" * 70)
    print("DEEPSHIELD AI — SCIENTIFIC RESEARCH PAPERS DOWNLOADER")
    print(f"Target Directory: {target_dir}")
    print(f"Total Papers to Download: {len(PAPERS_REGISTRY)}")
    print("=" * 70)

    downloaded = 0
    skipped = 0
    failed = 0

    catalog_records = []

    for idx, paper in enumerate(PAPERS_REGISTRY, 1):
        filename = paper["filename"]
        out_path = os.path.join(target_dir, filename)
        url = paper["pdf_url"]

        record = dict(paper)
        record["local_path"] = out_path
        record["downloaded"] = False

        if os.path.exists(out_path) and os.path.getsize(out_path) > 10000:
            print(f"[{idx}/{len(PAPERS_REGISTRY)}] Already exists: {filename} ({os.path.getsize(out_path) // 1024} KB)")
            record["downloaded"] = True
            record["file_size_kb"] = os.path.getsize(out_path) // 1024
            catalog_records.append(record)
            skipped += 1
            continue

        print(f"[{idx}/{len(PAPERS_REGISTRY)}] Downloading: {paper['title'][:50]}... from {url}")
        try:
            req = urllib.request.Request(url, headers=headers)
            with urllib.request.urlopen(req, timeout=25) as response, open(out_path, "wb") as out_file:
                content = response.read()
                out_file.write(content)
            
            size_kb = len(content) // 1024
            print(f"    -> Saved successfully: {filename} ({size_kb} KB)")
            record["downloaded"] = True
            record["file_size_kb"] = size_kb
            downloaded += 1
            time.sleep(1.2)  # Polite delay between arXiv requests
        except Exception as e:
            print(f"    -> Error downloading {url}: {e}")
            record["download_error"] = str(e)
            failed += 1

        catalog_records.append(record)

    # Save Catalog JSON
    catalog_path = "research/papers/papers_catalog.json"
    os.makedirs("research/papers", exist_ok=True)
    with open(catalog_path, "w", encoding="utf-8") as f:
        json.dump(catalog_records, f, indent=2)

    # Generate Markdown Directory Document
    md_path = "research/papers/PAPERS_DIRECTORY.md"
    generate_markdown_directory(catalog_records, md_path)

    print("\n" + "=" * 70)
    print(f"DOWNLOAD COMPLETE: {downloaded} Downloaded, {skipped} Already Cached, {failed} Failed")
    print(f"Catalog JSON: {catalog_path}")
    print(f"Directory Markdown: {md_path}")
    print("=" * 70)


def generate_markdown_directory(records, out_md_path):
    with open(out_md_path, "w", encoding="utf-8") as f:
        f.write("# DeepShield AI — Local Research Papers Archive\n\n")
        f.write("> **Systematic Open-Access Scientific Paper Archive**  \n")
        f.write(f"> **Total Cataloged Papers:** {len(records)}  \n")
        f.write(f"> **Archived Path:** `research/papers/pdfs/`  \n\n---\n\n")

        for r in records:
            status_icon = "✅ Local PDF Available" if r.get("downloaded") else "🔗 Online Link Only"
            f.write(f"### {r['title']}\n\n")
            f.write(f"- **Authors:** {r['authors']}\n")
            f.write(f"- **Venue & Year:** {r['venue']} ({r['year']})\n")
            f.write(f"- **Domain:** {r['domain']}\n")
            f.write(f"- **Archive Status:** {status_icon} (`{r['filename']}`)\n")
            f.write(f"- **Paper Links:** [arXiv Abstract]({r['arxiv_url']}) | [Direct PDF]({r['pdf_url']}) | [Official Code]({r['code_url']})\n\n---\n\n")


